#!/bin/bash
# Rebuilds setup.sql from schema.sql + functions.sql + policies.sql.
#
# Also stamps a schema revision: a number that goes up by one whenever the
# three source files change. setup.sql installs it as schema_version(), and
# src/lib/schemaRevision.js tells the app which revision it expects, so a
# trainer whose project runs an older setup.sql gets told to re-run it.
set -e
cd "$(dirname "${BASH_SOURCE[0]}")"

hash=$(cat schema.sql functions.sql policies.sql | sha256sum | cut -c1-16)
prev_hash=$(grep -m1 '^-- schema-hash: ' setup.sql 2>/dev/null | awk '{print $3}' || true)
prev_rev=$(grep -m1 '^-- schema-revision: ' setup.sql 2>/dev/null | awk '{print $3}' || true)
prev_rev=${prev_rev:-0}
if [ "$hash" = "$prev_hash" ]; then rev=$prev_rev; else rev=$((prev_rev + 1)); fi

{
  cat <<'HEAD'
-- BeefUp — full Supabase setup, applied in one go.
-- Concatenation of schema.sql + functions.sql + policies.sql, in dependency order.
-- Idempotent: safe to re-run against a project that already has some of this.
--
-- Paste the whole file into the Supabase SQL editor and run it.
HEAD
  echo "--"
  echo "-- Generated by build-setup.sh, do not edit by hand."
  echo "-- schema-revision: $rev"
  echo "-- schema-hash: $hash"
  printf '\nbegin;\n\n'
  for f in schema functions policies; do
    [ "$f" = schema ] || echo
    echo "-- ============================================================"
    echo "-- $f.sql"
    echo "-- ============================================================"
    cat "$f.sql"
  done
  cat <<SQL

-- ============================================================
-- schema_version() (generated)
-- ============================================================
-- The app compares this with the revision it was built for and asks the
-- trainer to re-run setup.sql when the project is behind.
create or replace function public.schema_version()
returns integer
language sql
immutable
set search_path = pg_catalog, pg_temp
as \$\$
  select $rev;
\$\$;

revoke all on function public.schema_version() from public;
grant execute on function public.schema_version() to authenticated;
SQL
  printf '\ncommit;\n'
} > setup.sql.new
mv setup.sql.new setup.sql

cat > ../src/lib/schemaRevision.js <<JS
// Generated by supabase/build-setup.sh, do not edit by hand.
export const SCHEMA_REVISION = $rev
JS
echo "setup.sql: revision $rev ($hash)"
